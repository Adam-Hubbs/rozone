# Spike: make roxygen docs in plain scripts visible to Ark (hover, signature
# help argument docs, completion docs, `?`) without executing the scripts.
#
# Run in a Positron R console:
#   source("spike/ark_help_injection.R")
#   rozone_spike_load("spike/example_script.R")
# Then, in an editor, hover `wmean` in `wmean(1:3)` and type `wmean(` after
# running `wmean <- function(x, w = rep(1, length(x))) NULL` in the console.
#
# Inline `r ...` code, ```{r} chunks and @eval* tags are stripped before
# roxygen2 sees them (see strip_r_code()), so docs never execute script code.

is_function_assignment <- function(expr) {
  is.call(expr) &&
    as.character(expr[[1]]) %in% c("<-", "=", "<<-") &&
    is.name(expr[[2]]) &&
    is.call(expr[[3]]) &&
    identical(expr[[3]][[1]], as.name("function"))
}

# Evaluating a `function(...)` literal only creates a closure; neither the body
# nor default arguments run, so this is safe for arbitrary scripts.
sandbox_functions <- function(path) {
  env <- new.env(parent = globalenv())
  parse(path, keep.source = FALSE) |>
    purrr::keep(is_function_assignment) |>
    purrr::walk(
      \(e) assign(as.character(e[[2]]), eval(e[[3]], env), envir = env)
    )
  env
}

# roxygen2 only enables markdown via DESCRIPTION or a per-block @md tag, and
# scripts have no DESCRIPTION.
with_markdown_tags <- function(lines) {
  is_roxy <- grepl("^\\s*#'", lines)
  block_end <- is_roxy & !dplyr::lead(is_roxy, default = FALSE)
  purrr::map2(
    lines,
    block_end,
    \(line, end) if (end) c(line, "#' @md") else line
  ) |>
    purrr::list_c()
}

# roxygen2 evaluates inline `r ...` code, ```{r} chunks, @eval/@evalRd/
# @evalNamespace tags and knits @includeRmd files while rendering. Strip all of them so documenting a script
# never runs any of its code; the stripped text is simply absent from the docs.
strip_r_code <- function(lines) {
  is_roxy <- grepl("^\\s*#'", lines)
  lines[is_roxy] <- gsub("`r [^`]*`", "", lines[is_roxy])
  body <- sub("^\\s*#'\\s?", "", lines)
  starts_tag <- is_roxy & startsWith(body, "@")
  starts_eval <- is_roxy &
    grepl("^@(eval(Rd|Namespace)?|includeRmd)\\b", body)
  opens_fence <- is_roxy & grepl("^```+\\s*\\{r", body)
  is_fence <- is_roxy & startsWith(body, "```")

  state <- purrr::accumulate(
    seq_along(lines),
    \(prev, i) {
      if (!is_roxy[i]) {
        "keep"
      } else if (prev == "fence") {
        if (is_fence[i]) "fence_end" else "fence"
      } else if (opens_fence[i]) {
        "fence"
      } else if (starts_eval[i] || (prev == "eval" && !starts_tag[i])) {
        "eval"
      } else {
        "keep"
      }
    },
    .init = "keep"
  )[-1]

  lines[state == "keep"]
}

script_topics <- function(path) {
  md_path <- tempfile(fileext = ".R")
  readLines(path) |>
    strip_r_code() |>
    with_markdown_tags() |>
    writeLines(md_path)
  env <- sandbox_functions(md_path)
  blocks <- roxygen2::parse_file(md_path, env = env)
  roxygen2::roclet_process(
    roxygen2::rd_roclet(),
    blocks,
    env,
    base_path = dirname(path)
  )
}

rozone_spike_load <- function(paths, pkg = "rozone.docs") {
  src <- file.path(tempfile("rozone-src"), pkg)
  dir.create(file.path(src, "man"), recursive = TRUE)
  writeLines(
    c(
      paste0("Package: ", pkg),
      "Version: 0.0.1",
      "Title: Documentation for Script Functions",
      "Description: Generated by rozone.",
      "License: MIT",
      "Encoding: UTF-8"
    ),
    file.path(src, "DESCRIPTION")
  )
  writeLines("", file.path(src, "NAMESPACE"))

  topics <- paths |> purrr::map(script_topics) |> purrr::list_flatten()
  purrr::iwalk(
    topics,
    \(topic, file) writeLines(format(topic), file.path(src, "man", file))
  )

  # A fresh library per build sidesteps R's in-memory lazy-load DB cache, which
  # otherwise reports the rebuilt help database as corrupt.
  lib <- tempfile("rozone-lib")
  dir.create(lib)
  status <- system2(
    file.path(R.home("bin"), "R"),
    c(
      "CMD",
      "INSTALL",
      "--no-test-load",
      "--no-byte-compile",
      "-l",
      shQuote(lib),
      shQuote(src)
    ),
    stdout = FALSE,
    stderr = FALSE
  )
  stopifnot(status == 0)

  if (isNamespaceLoaded(pkg)) unloadNamespace(pkg)
  loadNamespace(pkg, lib.loc = lib)
  invisible(names(topics))
}
