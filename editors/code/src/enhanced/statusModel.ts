import type { TierState } from "./api.ts";
import type { ViewState } from "./lifecycle.ts";

export interface StatusView {
  text: string;
  tooltip: string;
}

const BASE_REASONS: Record<Extract<TierState, { tier: "base" }>["reason"], string> = {
  untrusted: "Workspace is not trusted, so rozone never runs R. Trust the workspace for roxygen2-exact docs.",
  disabled: "The enhanced tier is turned off (rozone.enhanced.enabled).",
  "no-r": "No R installation was found. Set rozone.r.path or put Rscript on PATH.",
  "no-roxygen2": "The roxygen2 package is not installed. Install it for roxygen2-exact docs.",
  crashed: "The R sidecar crashed repeatedly. Reload the window or run 'rozone: Restart R Sidecar'.",
  virtual: "Virtual workspaces are not supported by the enhanced tier.",
};

export function describeState(state: ViewState): StatusView {
  switch (state.tier) {
    case "base":
      return { text: "rozone: base", tooltip: `Base tier: ${BASE_REASONS[state.reason]}` };
    case "starting":
      return { text: "rozone: base", tooltip: "Starting the R sidecar..." };
    case "enhanced":
      return { text: "rozone: enhanced", tooltip: "Enhanced tier: docs are generated by roxygen2 in a background R process." };
    case "enhanced+help":
      return {
        text: "rozone: enhanced + help",
        tooltip: "Enhanced tier: roxygen2 docs, also loaded into the R session for ?fn, the Help pane and completions.",
      };
  }
}
